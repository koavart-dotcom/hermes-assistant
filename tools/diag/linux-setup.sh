#!/usr/bin/env bash
# Prepare a Linux host for Hermes read-only diagnostics (docs/DIAG.md). Run as root:
#
#   sudo bash linux-setup.sh '<public key from `hermesctl diag-key`>' <hermes-server-ip> [--fix "nginx php8.2-fpm"]
#
# With --fix the user may also run exactly the fix commands of the web panel
# (crates/hermes-core/src/fix.rs) through sudo: restart of the listed services,
# journalctl --vacuum-size=500M and logrotate -f. Nothing else; the rules are in
# /etc/sudoers.d/hermes-diag and checked with visudo. Without --fix that file is removed.
#
# Creates the user hermes-diag without a password and without sudo, adds it to the
# groups that may read the system journal (systemd-journal, adm), and authorises the
# Hermes service key only from the Hermes server, without forwarding or a terminal.
# What the service runs is a fixed catalogue (crates/hermes-core/src/diag.rs):
# uptime/free, df, du, ps, systemctl --failed, journalctl, last, ss.
set -euo pipefail

KEY="${1:?public key (ssh-ed25519 ...)}"
FROM="${2:?IP of the Hermes server}"
FIX_SERVICES=""
if [[ "${3:-}" == "--fix" ]]; then
  FIX_SERVICES="${4:?--fix needs a list of services, e.g. \"nginx php8.2-fpm\"}"
fi
USER_NAME="hermes-diag"

[[ "$(id -u)" -eq 0 ]] || { echo "run as root" >&2; exit 1; }
[[ "$KEY" == ssh-ed25519\ * ]] || { echo "expected an ssh-ed25519 public key" >&2; exit 1; }
[[ "$FROM" =~ ^[0-9a-fA-F:.]+$ ]] || { echo "server address must be an IP" >&2; exit 1; }

if ! id "$USER_NAME" >/dev/null 2>&1; then
  useradd --system --create-home --shell /bin/bash --comment "Hermes read-only diagnostics" "$USER_NAME"
fi
passwd -l "$USER_NAME" >/dev/null
for g in systemd-journal adm; do
  getent group "$g" >/dev/null && usermod -aG "$g" "$USER_NAME"
done

home="$(getent passwd "$USER_NAME" | cut -d: -f6)"
install -d -m 700 -o "$USER_NAME" -g "$USER_NAME" "$home/.ssh"
opts="from=\"$FROM\",no-port-forwarding,no-agent-forwarding,no-X11-forwarding,no-pty"
printf '%s %s\n' "$opts" "$KEY" > "$home/.ssh/authorized_keys"
chown "$USER_NAME:$USER_NAME" "$home/.ssh/authorized_keys"
chmod 600 "$home/.ssh/authorized_keys"

SUDOERS=/etc/sudoers.d/hermes-diag
if [[ -n "$FIX_SERVICES" ]]; then
  tmp="$(mktemp)"
  {
    echo "# Hermes web panel fixes (crates/hermes-core/src/fix.rs). Generated by linux-setup.sh."
    for svc in $FIX_SERVICES; do
      [[ "$svc" =~ ^[A-Za-z0-9@._-]+$ && "$svc" != -* ]] || { echo "bad service name: $svc" >&2; rm -f "$tmp"; exit 1; }
      echo "$USER_NAME ALL=(root) NOPASSWD: /usr/bin/systemctl restart $svc"
    done
    echo "$USER_NAME ALL=(root) NOPASSWD: /usr/bin/journalctl --vacuum-size=500M"
    echo "$USER_NAME ALL=(root) NOPASSWD: /usr/sbin/logrotate -f /etc/logrotate.conf"
  } > "$tmp"
  visudo -cf "$tmp" >/dev/null || { echo "sudoers check failed" >&2; rm -f "$tmp"; exit 1; }
  install -m 440 -o root -g root "$tmp" "$SUDOERS"
  rm -f "$tmp"
  echo "fixes allowed: restart of $FIX_SERVICES, journal vacuum, logrotate ($SUDOERS)"
else
  rm -f "$SUDOERS"
fi

echo "ok: $USER_NAME ready; groups: $(id -nG "$USER_NAME")"
echo "check from the Hermes server: hermesctl diag-run $(hostname)"
